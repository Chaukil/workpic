const task = { job: { id: 'job', title: 'Review', time: '09:00', duration: 60 }, originDate: '2026-11-02' };
const moved = { ...task, overrideTime: '14:00', shiftedFrom: '2026-11-02' };
const days = houseDays(houseWeekStart(new Date(2026, 10, 5)), { '2026-11-05': [moved, task] }, { off: { '2026-11-06': { reason: 'SO' } } });
assert.equal(days.length, 7);assert.equal(days[6].floor, 7);assert.equal(days[6].label, 'Chủ nhật');
assert.equal(days[4].off, 'SO');assert.equal(days[3].entries[1].originDate, '2026-11-02');
assert.equal(houseTaskState(task,'2026-11-05',new Date(2026,10,5,8,59)), 'upcoming');
assert.equal(houseTaskState(task,'2026-11-05',new Date(2026,10,5,9)), 'active');
assert.equal(houseTaskState(task,'2026-11-05',new Date(2026,10,5,10)), 'past');
assert.equal(houseTaskState(moved,'2026-11-05',new Date(2026,10,5,10)), 'upcoming');
assert.equal(houseTaskState({...task,completed:true},'2026-11-05',new Date(2026,10,5,9)), 'completed');
const untimed = {job:{title:'Untimed'}};
assert.equal(houseTaskState(untimed,'2026-11-04',new Date(2026,10,5)), 'past');
assert.equal(houseTaskState(untimed,'2026-11-05',new Date(2026,10,5)), 'active');
assert.equal(houseTaskState(untimed,'2026-11-06',new Date(2026,10,5)), 'upcoming');
assert.equal(houseLights(days[3],new Date(2026,10,5,15)).on,false,'floor goes dark after final job');
assert.equal(houseLights(days[3],new Date(2026,10,5,15),true).on,true,'manual inspection of expired tasks');
assert.equal(houseLights(days[3],new Date(2026,10,5,9)).on,true);
assert.equal(houseLights(days[3],new Date(2026,10,6)).on,false,'previous day turns off');
assert.equal(houseLights(days[3],new Date(2026,10,4)).on,false,'future day stays off until switched on');
assert.equal(houseLights({key:'2026-11-05',entries:[]},new Date(2026,10,5)).on,false);
assert.equal(houseTaskState({job:{time:'23:30',duration:90}},'2026-11-05',new Date(2026,10,6,0,1)), 'past','day rollover switches off even an overnight room');

